def _build_product_catalog() -> str:
    """Load all products from DB and build a compact text catalog for the AI prompt."""
    db = SessionLocal()
    try:
        all_products = db.query(Product).all()
        all_categories = db.query(Category).all()

        cat_map = {c.slug: c.title_ru for c in all_categories}

        global PRODUCT_IMAGE_MAP
        PRODUCT_IMAGE_MAP = {}

        # Group products by category
        grouped: dict[str, list[str]] = {}
        for p in all_products:
            cat_name = cat_map.get(p.category_slug, p.category_slug or "Без категории")
            entry = p.title
            if p.article:
                entry += f" (арт. {p.article})"
            if p.size:
                entry += f", {p.size}"

            # Parse color variants for catalog text
            colors = []
            color_imgs = []
            if p.colors_json:
                try:
                    color_list = json.loads(p.colors_json)
                    for c in color_list:
                        cname = c.get("name", "")
                        if cname:
                            colors.append(cname)
                        cimg = c.get("img", "")
                        if cimg:
                            color_imgs.append({"title": f"{p.title} ({cname})", "url": cimg})
                except (json.JSONDecodeError, TypeError):
                    pass

            if colors:
                entry += f" | Цвета: {', '.join(colors)}"

            # Flag if product has photos (without showing paths)
            has_photo = bool(p.img) or bool(color_imgs)
            if has_photo:
                entry += " [есть фото]"

            grouped.setdefault(cat_name, []).append(entry)

            # Build image map: title -> list of images (main + color variants)
            images_for_product = []
            if p.img:
                images_for_product.append({"title": p.title, "url": p.img})
            images_for_product.extend(color_imgs)
            if images_for_product:
                PRODUCT_IMAGE_MAP[p.title.lower()] = images_for_product

        lines = ["КАТАЛОГ ТОВАРОВ (актуальный список из базы данных):"]
        for cat_name, items in grouped.items():
            lines.append(f"\n📁 {cat_name} ({len(items)} товаров):")
            for item in items:
                lines.append(f"  • {item}")

        lines.append(f"\nВсего товаров в каталоге: {len(all_products)}")
        return "\n".join(lines)
    except Exception as e:
        print(f"⚠️ Не удалось загрузить каталог для AI: {e}")
        return "Каталог товаров временно недоступен."
    finally:
        db.close()


